"""Accounts, consent, and location

Seven tables, the whole of Phase 1:

* `users` — a neighbour. No password: identity is a phone number proved by a
  one-time code. The home location sits inline (four H3 resolutions plus the cell
  centroid) because only the current one is ever kept.
* `consents` — append-only record of what was agreed to, when, and to which
  document version, as the Data Protection Act requires.
* `blocks` — one row per block, filtered through one shared check everywhere.
* `device_sessions` — hashed refresh tokens, with the family chain that makes
  reuse detection possible.
* `areas` — seeded polygons that give an approximate location a human name.
* `cell_activity` — per-cell population counts the radius engine reads.
* `audit_events` — append-only trail of consequential actions.

Autogenerated, then reviewed. Four things were checked by hand rather than
trusted:

1. **Geospatial operations use GeoAlchemy2's helpers**
   (`create_geospatial_table`, `create_geospatial_index`), so the GiST indexes on
   `areas.boundary` and `users.home_centroid` are managed by PostGIS rather than
   created as plain indexes Alembic would then mismanage.
2. **The trigram GIN indexes** on `areas.name` and `users.display_name` carry
   their `gin_trgm_ops` operator class. Without it the index is built happily and
   every similarity search silently ignores it and sequentially scans.
3. **Boolean server defaults render as literals.** The first draft of the models
   used `func.true()`, which emits `DEFAULT true()` — not valid SQL, and it failed
   on the first `CREATE TABLE`. They are `text("true")` now.
4. **The downgrade is symmetric**: every table and spatial index created here is
   dropped, verified by running upgrade, downgrade, and upgrade again.

Revision ID: 0002
Revises: 0001
Created: 2026-10-12
"""

