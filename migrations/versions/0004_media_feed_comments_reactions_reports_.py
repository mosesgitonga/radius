"""Media, feed, comments, reactions, reports, idempotency

Nine tables, the whole of Phase 2:

* `media_assets` — one row per upload, from presigned URL to served variants.
* `posts`, `post_images` — the neighbourhood feed. Posts carry their own
  location, so the feed query is one spatial predicate on one GiST index.
* `stories`, `story_views` — 24-hour content and its viewer list.
* `comments` — one level of replies, enforced by the service.
* `reactions` — one per user per post or comment.
* `reports` — the moderation queue, with priority bands so Phase 8 can order by
  harm rather than by arrival.
* `idempotency_records` — the `Idempotency-Key` support deferred from Phase 0.

Autogenerated, then reviewed. Checked by hand:

1. `posts` and `stories` are created with GeoAlchemy2's geospatial helpers, so
   their centroid GiST indexes are managed by PostGIS.
2. The `reactions` check constraint allows exactly one of `post_id`/`comment_id`,
   and the two partial unique constraints make a second reaction from the same
   user impossible rather than merely discouraged.
3. The `stories` check constraint ties `kind` to its content, so an image story
   cannot exist without an image.
4. `post_images.media_id` is `RESTRICT`, not `CASCADE`: an image must not vanish
   from under a post.
5. The composite index on `posts (status, created_at, id)` is what the keyset
   paginator needs; without the `id` tail, posts sharing a timestamp would appear
   on two pages or none.
6. Upgrade, downgrade, and upgrade again all run on an empty database.

Revision ID: 0004
Revises: 0003
Created: 2026-10-12
"""

